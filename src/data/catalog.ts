export function getProductsForCollection(slug: CollectionSlug): Product[] {
  return PRODUCTS.filter((p) => {
    if (p.collectionSlug === slug) return true;
    if (slug === 'bridal-collection' && (p.isBridal || p.occasion === 'Bridal')) return true;
    if (slug === 'festive-collection' && p.occasion === 'Festive') return true;
    if (
      slug === 'handloom-collection' &&
      ['Paithani Silk', 'Tussar Silk', 'Chanderi Silk-Cotton', 'Jamdani Muslin', 'Patola Silk'].includes(
        p.fabric
      )
    )
      return true;
    if (
      slug === 'contemporary-sarees' &&
      ['Tissue Silk', 'Silk Organza', 'Mysore Crepe Silk'].includes(p.fabric)
    )
      return true;
    return false;
  });
}

export function getCollectionBySlug(slug: string): CollectionInfo | undefined {
  return COLLECTIONS.find((c) => c.slug === (slug as CollectionSlug));
}

export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}
